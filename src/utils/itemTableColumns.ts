/**
 * أعمدة جدول البنود التي تُكتب مباشرةً — بلا وضع تعديل وبلا حجزٍ للمسطرة.
 *
 * ## لماذا وُجد وضع التعديل أصلاً
 * جدول البنود يحمل سلوكاً ذا وضعين: خلية تصل إليها بالكيبورد تبدأ في **وضع
 * التنقّل** — لا مؤشّر كتابة، والحروف مرفوضة، والمسطرة محجوزة لتحديد الصف
 * وحذفه (`useSpaceToDelete`). ولا تكتب فيها حتى تدخل **وضع التعديل** بنقرة
 * ماوس أو ضغطة Shift.
 *
 * وهذا مفيدٌ في عمود المنتج: اسمٌ نصّي طويل، والمسطرة فيه أداةُ حذفٍ لا حرف.
 *
 * ## ولماذا لا يصلح في الأعمدة الرقمية
 * الكمية والسعر والسعر الأجنبي والإجمالي أرقامٌ تُبدَّل بضغطةٍ واحدة. فأن
 * تنتقل إلى «الكمية» ثم تضغط Shift ثم تكتب — ثلاث حركاتٍ مكان واحدة، في
 * شاشةٍ يُدخَل فيها مئة بند. وصاحب المستودع طلبها صراحةً: «تغيّر الرقم على
 * طول… لسرعة الحركة».
 *
 * فهذه الأعمدة `<input>` عادية: مؤشّرٌ ظاهر، وكتابةٌ فورية، ومسطرةٌ تكتب
 * مسافة. والوصول إليها بالكيبورد **يحدّد** محتواها فتستبدله الضغطة الأولى.
 *
 * والحذف بالمسطرة يبقى حيّاً من عمود المنتج — وهو موضعه الطبيعي: تحدّد الصف
 * من اسمه لا من كمّيته.
 *
 * المصدر الواحد هنا لأن ثلاثة ملفات تحتاج القائمة نفسها (`spaceColumnNav`،
 * `useSpaceToDelete`، `useInvoiceKeyboardNav`) — ونسخُها في كلٍّ منها هو
 * بالضبط النمط الذي كرّر أعطال هذا المشروع.
 */

/**
 * أعمدة رقمية تُكتب مباشرةً في كل جداول البنود (فواتير، عروض، مشتريات،
 * مرتجعات) — وفي جدول كميات المنتجات: الجردُ إدخالٌ سريع كإدخال البنود.
 */
export const FREE_TYPING_COLS = [
  "quantity",
  "min_stock",
  "unit_price",
  "foreign_price",
  "total",
  "price",
  "exchange_rate",
] as const;

const FREE_SET = new Set<string>(FREE_TYPING_COLS as readonly string[]);

/** هل هذه الخلية من الأعمدة التي تُكتب مباشرةً؟ */
export function isFreeTypingCol(el: Element | null | undefined): boolean {
  if (!el) return false;
  const col = (el as HTMLElement).getAttribute?.("data-nav-col");
  return !!col && FREE_SET.has(col);
}

/**
 * تحديد محتوى الخلية الرقمية عند الوصول إليها بالكيبورد.
 *
 * بلا تحديد، من ينتقل إلى كمّيةٍ قيمتها 12 ليضع 5 يكتب «512» أو «125» بحسب
 * موضع المؤشّر، فيمسح ثم يكتب. الوصول بالمفاتيح نيّةُ استبدالٍ لا نيّةُ
 * تصحيحٍ داخل الرقم — ولا يُطبَّق على نقر الماوس: من ينقر موضعاً يريده.
 */
export function selectIfFreeTyping(el: Element | null | undefined): void {
  if (!isFreeTypingCol(el)) return;
  const input = el as HTMLInputElement;
  if (typeof input.select !== "function") return;
  try { input.select(); } catch { /* بعض أنواع الحقول لا تدعم التحديد */ }
}
