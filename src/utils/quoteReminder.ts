/**
 * تنبيه عرض السعر — رسالةٌ واحدة تُرسل لرقم العميل المسجَّل في العرض.
 *
 * ## ما طلبه صاحب المستودع
 * «أريد زرّ تنبيه في عرض السعر وعرض السعر الجانبي يرسل واتساب بالنصّ هذا…
 * تذهب في رقم العميل على طول، المسجَّل المحدَّد في عرض السعر».
 *
 * ## لماذا النصّ هنا لا في الأزرار
 * الزرّ يظهر في خمس شاشات (إنشاء العرض، والجانبي، وإدارة الاثنين، وشاشتا
 * العرض). ونسخُ النصّ خمس مرّات يعني أن تصحيح كلمةٍ فيه يُصحّح موضعاً ويترك
 * أربعة — وهو النمط الذي كرّر أعطال هذا المشروع. فالنصّ ثابتٌ واحد، والزرّ
 * ينادي دالّةً واحدة.
 *
 * ## و«على طول» شرطٌ لا وصف
 * الرسالة تفتح واتساب على **رقم العميل مباشرةً** — لا حوارَ اختيار، ولا نسخَ
 * ولصق. ومصدر الرقم `pickCustomerWhatsApp`: حقل `whatsapp` أوّلاً ثم `phone`،
 * وهو المصدر المعتمد في النظام كلّه. فبلا رقمٍ صالح يُقال ذلك صراحةً — أهون
 * من فتح واتساب على فراغ فيظنّ المستخدم أنه أرسل.
 */
import { toast } from "sonner";
import { openWhatsApp, pickCustomerWhatsApp } from "@/utils/whatsapp";

/**
 * نصّ التنبيه — كما كتبه صاحب المستودع حرفاً بحرف.
 *
 * لا يُعاد صوغه ولا تُضاف إليه تحيّة: هو رسالةُ متابعةٍ تُرسَل بعد عرضٍ سبق
 * إرساله، فالعميل يعرف عمّا تتحدّث.
 */
export const QUOTE_REMINDER_TEXT = [
  "📋 نرجو مراجعة الفاتورة وإفادتنا اليوم.",
  "",
  "⏳ إذا كنت ترغب في التعديل أو عدم إكمال الطلب، نرجو إبلاغنا لفك الحجز، لأن بعض الأصناف محدودة وقد تنفد.",
  "",
  "🤝 شكرًا لتعاونك، وفي انتظار ردك.",
].join("\n");

export interface QuoteReminderCustomer {
  name?: string | null;
  phone?: string | null;
  whatsapp?: string | null;
}

/**
 * يفتح واتساب برسالة التنبيه على رقم العميل المسجَّل في العرض.
 *
 * @returns `true` إن فُتح واتساب فعلاً، و`false` إن لم يكن للعميل رقمٌ صالح.
 */
export function sendQuoteReminder(customer: QuoteReminderCustomer | null | undefined): boolean {
  const phone = pickCustomerWhatsApp(customer);
  if (!phone) {
    toast.error("لا يوجد رقم واتساب صالح للعميل المحدَّد في عرض السعر");
    return false;
  }
  openWhatsApp(phone, QUOTE_REMINDER_TEXT);
  return true;
}
