/**
 * «إجمالي عدد القطع» — مجموعُ الأرقام المكتوبة في أوّل الأسطر.
 *
 * ## القاعدة كما قرّرها صاحبُ المستودع
 * «عدد القطع على الرقم في الأول قبل كلمة كرتونة كبيرة»، و«فمثلاً كتبت 5
 * كرتونة كبيرة تظهر إجمالي القطع 5».
 *
 * فالسطرُ الواحد يُعدّ بما بدأ به، مهما كان فيه:
 *
 *     1 كرتونة صغيرة باكم فرامل *50   ⇒ 1
 *     1 بطارية جي ان YAYE *8          ⇒ 1
 *     1 كرتونة كبيرة                   ⇒ 1
 *     5 كرتونة كبيرة                   ⇒ 5
 *
 * وستّةُ أسطرٍ تبدأ كلٌّ منها بـ1 مجموعُها **6**. وعلامةُ ‎*‎N بعد الاسم
 * وصفٌ لما في الطرد الواحد، لا عاملُ ضربٍ في المجموع.
 *
 * ## وقد ضُرب هذا المجموعُ في ‎*‎N مرّةً فأخطأ
 * حُسب قبلُ `packs × pieces_per_pack` ظنّاً أنّ «القطع» قطعُ البضاعة داخل
 * الطرود، فخرجت الورقةُ بـ99 حيث يريد صاحبُها 6 — ثمّ نُقل الخطأُ إلى تقرير
 * الإرسال بحجّة توحيد الرقمين. فصُحّح الاثنان إلى القاعدة أعلاه.
 *
 * ## والمصدرُ واحدٌ لسببٍ بنيويّ
 * الرقمُ المطبوع في أوّل السطر والرقمُ في المجموع **يُشتقّان من هذه الدالّة
 * نفسِها**. فلا يمكن أن يختلفا: من غيّر أحدَهما غيّر الآخر.
 *
 * يحرسه `src/test/packagingPiecesCount.test.ts`.
 */
export function packagingCountOf(r: {
  packs_count?: any; quantity?: any;
}): number {
  // العددُ المسجَّل للطرود، فإن غاب فالكمية — وهي ما كانت تُدخَل قبل العمود.
  const packs = Number(r.packs_count || 0);
  if (packs > 0) return packs;
  return Number(r.quantity || 0);
}

/** مجموعُ أرقام الأسطر — بالقاعدة نفسها، فلا يُجمع بيدٍ أخرى. */
export function packagingCountSum(rows: Array<{
  packs_count?: any; quantity?: any;
}> | null | undefined): number {
  return (rows || []).reduce((s, r) => s + packagingCountOf(r), 0);
}
