/**
 * منطق موحّد لفلترة اقتراحات المنتجات في شاشات إدخال البنود كلّها:
 * الفواتير وفواتير الكاش وعروض الأسعار والعروض الجانبية.
 *
 * القواعد:
 * - بحث فارغ ⇒ لا اقتراحات.
 * - فلتر اختياري بحسب المخزن (warehouseId) — يُطبَّق فقط إذا مُرِّر.
 * - إزالة التكرار بحسب id (نفس المنتج لا يظهر مرتين).
 * - حد أقصى 10 نتائج.
 *
 * ## «يبدأ بـ» لا «يحتوي على»
 * كانت المطابقة على **بداية أي كلمة** داخل الاسم، فكتابة «است» تُظهر
 * «بوري است» كما تُظهر «استانلس» — قائمةٌ نصفُها لا يبدأ بما كُتب، ويضيع
 * المقصود بينها. وطلب صاحب المستودع: «كتبت است تظهر كل المنتجات التي تبدأ
 * بـاست فقط».
 *
 * فصارت المطابقة على **بداية الاسم أو الرمز** وحدها. وثمنُها معلوم: من لا
 * يحفظ أوّل كلمةٍ في اسمٍ طويل لن يجده بكلمةٍ من وسطه — وهذا اختيارُ صاحب
 * المستودع، وهو يعرف أسماء بضاعته.
 *
 * ملاحظة: لا نستبعد المنتجات المُضافة فعلياً إلى الصفوف، حتى يبقى البحث
 * "حيّاً" ويستطيع المستخدم تأكيد وجوده — وتظهر له رسالة "مُضاف مسبقاً"
 * عند المحاولة فعلياً (يُتعامَل معها في pickProductIntoRow).
 */
import { leadsWithAny } from "./searchMatch";

export interface ProductLike {
  id: string;
  name: string;
  sku?: string | null;
  warehouse_id?: string | null;
}

export function productMatches<T extends ProductLike>(
  products: T[],
  query: string,
  warehouseId?: string | null,
): T[] {
  if (!query.trim()) return [];
  const seen = new Set<string>();
  return products
    .filter((p) => !warehouseId || p.warehouse_id === warehouseId)
    // بداية الاسم أو الرمز وحدها — لا بداية كلمةٍ في وسط الاسم
    .filter((p) => leadsWithAny([p.name, p.sku], query))
    .filter((p) => {
      if (seen.has(p.id)) return false;
      seen.add(p.id);
      return true;
    })
    // الترتيب على حاله — لا تقفز النتائج بين ضغطتين
    .slice(0, 10);
}
