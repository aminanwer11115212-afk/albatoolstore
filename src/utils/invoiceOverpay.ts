/**
 * فائضُ الدفع على فاتورة — ما دُفع فوق قيمتها.
 *
 * ## ما بلّغ عنه صاحبُ المستودع
 * «المدفوع لمّا يكون أكتر من الفاتورة، الفاتورة جوّه بتظهر خالصة. مثال:
 * الفاتورة ٢٠٠٠ والمدفوع ٢١٠٠ — كده باقي للعميل ١٠٠ له، ويلّا الفاتورة
 * بتظهر خالصة. عدّل تظهر في كل مكان إنّه له ١٠٠».
 *
 * ## ولمَ اختفى الفائض
 * `splitPayment` تقسم الدفعة قسمين: ما يُقفل الفاتورة (`applied`) وما زاد
 * (`overpay`). فـ`paid_amount` **مقصوصٌ عند الإجمالي** — 2000 لا 2100 —
 * والزائدُ يُكتب قيدَ `customer_credit` مربوطاً بالفاتورة بـ`reference_id`.
 *
 * والقصُّ صحيحٌ في موضعه: `invoiceDue` تقول «الفائضُ ليس ديناً سالباً على
 * الفاتورة، مكانه رصيد العميل». لكنّ أثرَه أنّ الفاتورة تُعلن نفسَها خالصةً
 * ولا يبقى فيها أثرٌ للمئة — فيقرؤها صاحبُها «تمّت» ولا يعلم أنّ للعميل عنده
 * بقيّة.
 *
 * ## والرقمُ موجودٌ لا يحتاج حساباً جديداً
 * القيدُ مكتوبٌ بالفعل ومربوطٌ بالفاتورة. فهذه الوحدة تقرؤه ولا تشتقّه —
 * ولا تُغيّر شيئاً في الحساب: `paid_amount` كما هو، والرصيدُ كما هو. إنّما
 * يُعرض ما كان مخفيّاً.
 *
 * يحرسه `src/test/invoiceOverpayDisplay.test.ts`.
 */

/** قيدٌ من جدول المعاملات — أقلُّ ما نحتاج منه. */
export interface CreditTx {
  category?: string | null;
  amount?: number | null;
  reference_id?: string | null;
}

/**
 * الفائضُ المسجَّل على فاتورةٍ بعينها.
 *
 * ويُجمع الموجبُ وحده: قيودُ **استهلاك** الرصيد سالبةٌ وتحمل `reference_id`
 * الفاتورة التي سُدِّدت منه — لا الفاتورة التي وُلد منها. فجمعُها هنا يخصم
 * من فائض فاتورةٍ ما استُهلك على أخرى.
 */
export function invoiceOverpay(invoiceId: string, txs: CreditTx[] | null | undefined): number {
  if (!invoiceId || !txs?.length) return 0;
  const sum = txs.reduce((s, t) => {
    if (t?.category !== "customer_credit") return s;
    if (String(t?.reference_id || "") !== invoiceId) return s;
    const n = Number(t?.amount) || 0;
    return n > 0 ? s + n : s;
  }, 0);
  return Math.round(sum * 100) / 100;
}
