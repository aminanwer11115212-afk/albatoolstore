-- اسمُ المسؤول في ترويسة الورقة
--
-- أرسل صاحبُ المستودع شكلَ الترويسة مصوَّراً: تحت اسم الشركة سطرٌ واحد فيه
-- الهاتفُ والمسؤولُ والعنوان، كلٌّ بعلامته:
--
--     0909605576  |  مينا جابر  |  عطبرة
--
-- والهاتفُ والعنوان موجودان في `company_settings`. أمّا اسمُ المسؤول فلا عمود
-- له — فهذا العمود.
--
-- ولا أثرَ له على شيءٍ قائم: نصٌّ اختياريّ فارغٌ افتراضاً، والورقةُ تتخطّى
-- الحقلَ الفارغ فلا تترك علامةً معلّقةً ولا فاصلاً زائداً. فمن لم يملأه رأى
-- ترويسته كما كانت.
--
-- ⚠️ لا تُطبَّق هذه الهجرة من بيئة التطوير: الوصول إلى supabase.co محجوبٌ
-- بسياسة الوكيل، والمفتاحُ المتاح (anon) لا يملك تنفيذ DDL. فتُنفَّذ يدوياً
-- من SQL Editor في لوحة Supabase.

ALTER TABLE public.company_settings
  ADD COLUMN IF NOT EXISTS manager_name text;

COMMENT ON COLUMN public.company_settings.manager_name IS
  'اسم المسؤول — يظهر في شريط بيانات الشركة أعلى ورقة الفاتورة/العرض/المرتجع';
